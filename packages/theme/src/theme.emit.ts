import {
  colorRoles,
  componentTokenNames,
  scaleTokenNames,
  shadowRoles,
  typeStepNames
} from "./theme.roles";
import type {
  ColorRole,
  ModeTokenName,
  ScaleTokenName,
  ThemeDefinition,
  ThemeMode,
  TypeStep,
  TypeStepName
} from "./theme.schema";

const HEADER = "Generated by pnpm theme:build from @repo/theme. Do not edit.";

type Entry = readonly [name: string, value: string];

/** Web type utilities and the type step each one sets. Mobile uses the same names. */
export const typeUtilities = {
  "heading-xl": "heading-xlarge",
  "heading-lg": "heading-large",
  "heading-md": "heading-medium",
  "heading-sm": "heading-small",
  "heading-xs": "heading-xsmall",
  "heading-xxs": "heading-xxsmall",
  "body-lg": "body-large",
  body: "body",
  "body-sm": "body-small",
  "body-xs": "body-xsmall"
} as const satisfies Record<string, TypeStepName>;

const radiusUtilities = {
  sm: "radius-050",
  md: "radius-100",
  lg: "radius-200",
  xl: "radius-300"
} as const satisfies Record<string, ScaleTokenName>;

const fontWeightUtilities = {
  normal: "font-weight-regular",
  medium: "font-weight-medium",
  semibold: "font-weight-semibold",
  bold: "font-weight-bold"
} as const satisfies Record<string, ScaleTokenName>;

/** Component token utilities: rounded-card, shadow-card, p-card, font-button, border-ds-field-border. */
const componentUtilities = [
  ["--radius-button", "button-radius"],
  ["--radius-field", "field-radius"],
  ["--radius-card", "card-radius"],
  ["--radius-overlay", "overlay-radius"],
  ["--radius-dialog", "dialog-radius"],
  ["--radius-badge", "badge-radius"],
  ["--shadow-card", "card-shadow"],
  ["--spacing-card", "card-padding"],
  ["--font-weight-button", "button-font-weight"],
  ["--color-ds-field-border", "field-border"]
] as const;

const variable = (name: string): string => `var(--ds-${name})`;

export function fontShorthand(step: TypeStep): string {
  return `${step.weight} ${step.size}/${step.lineHeight} ${variable(`font-family-${step.family}`)}`;
}

/** The utility color name: the token name, with `background-` shortened to `bg-`. */
export function colorUtilityName(role: ColorRole): string {
  return role === "background-default" ? "ds-bg" : `ds-${role.replace(/^background-/, "bg-")}`;
}

function spacingUtilities(): Entry[] {
  return scaleTokenNames.flatMap((name): Entry[] => {
    const space = /^space-(.+)$/.exec(name)?.[1];
    const control = /^control-(.+)$/.exec(name)?.[1];

    if (space) {
      return [[`ds-${space}`, name]];
    }

    return control ? [[`ds-control-${control}`, name]] : [];
  });
}

function scaleEntries(theme: ThemeDefinition): Entry[] {
  return [
    ...scaleTokenNames.map((name): Entry => [name, theme.scale[name]]),
    ...typeStepNames.map((name): Entry => [`font-${name}`, fontShorthand(theme.type[name])]),
    ...componentTokenNames.map((name): Entry => [name, theme.components[name]])
  ];
}

function modeEntries(mode: ThemeMode, names: readonly ModeTokenName[]): Entry[] {
  return names.map((name): Entry => [name, mode[name]]);
}

function block(selector: string, lines: readonly string[]): string {
  return `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}`;
}

const declare = ([name, value]: Entry): string => `--ds-${name}: ${value};`;

/**
 * One theme as two rule sets: its light values with the scale, then its dark values. The
 * default theme also owns :root, so a page with no data-theme, or an unknown one, gets it.
 */
function themeRules(theme: ThemeDefinition, isDefault: boolean): string[] {
  const named = `[data-theme="${theme.name}"]`;
  const modeNames = [...colorRoles, ...shadowRoles];

  return [
    block(isDefault ? `:root,\n${named}` : named, [
      "color-scheme: light;",
      ...scaleEntries(theme).map(declare),
      ...modeEntries(theme.modes.light, modeNames).map(declare)
    ]),
    block(isDefault ? `[data-color-mode="dark"]` : `${named}[data-color-mode="dark"]`, [
      "color-scheme: dark;",
      ...modeEntries(theme.modes.dark, modeNames).map(declare)
    ])
  ];
}

/**
 * CSS for a theme that is not registered, such as a lab theme, under [data-theme="<name>"].
 * The utilities already read the tokens, so injecting this CSS is enough to apply the theme.
 */
export function emitThemeCss(theme: ThemeDefinition): string {
  return themeRules(theme, false).join("\n\n");
}

/**
 * packages/ui/src/styles/tokens.generated.css: every registered theme and the Tailwind
 * utilities that read the tokens. data-theme on an element picks the theme for its subtree;
 * data-color-mode="dark" on the same element picks its dark values.
 */
export function emitWebTokens(
  themes: readonly ThemeDefinition[],
  defaultTheme: ThemeDefinition
): string {
  const theme = defaultTheme;
  const reset = block("@theme", [
    "--color-*: initial;",
    "--font-weight-*: initial;",
    "--radius-*: initial;",
    "--shadow-*: initial;",
    "--text-*: initial;"
  ]);
  const utilities = block("@theme inline", [
    `--font-sans: ${variable("font-family-sans")};`,
    `--font-mono: ${variable("font-family-mono")};`,
    ...Object.entries(fontWeightUtilities).map(
      ([utility, token]) => `--font-weight-${utility}: ${variable(token)};`
    ),
    ...Object.entries(radiusUtilities).map(
      ([utility, token]) => `--radius-${utility}: ${variable(token)};`
    ),
    ...shadowRoles.map((role) => `--${role}: ${variable(role)};`),
    ...colorRoles.map((role) => `--color-${colorUtilityName(role)}: ${variable(role)};`),
    ...spacingUtilities().map(([utility, token]) => `--spacing-${utility}: ${variable(token)};`),
    ...componentUtilities.map(([utility, token]) => `${utility}: ${variable(token)};`)
  ]);
  const typeComment = [
    "/*",
    " * Each type utility sets the whole font from its token. font-family comes first only so",
    " * that Tailwind sorts these utilities before font-* and leading-* utilities, which then",
    " * still override the weight and the line height.",
    " */"
  ].join("\n");
  const types = Object.entries(typeUtilities).map(([utility, step]) =>
    block(`@utility text-${utility}`, [
      `font-family: ${variable(`font-family-${theme.type[step].family}`)};`,
      `font: ${variable(`font-${step}`)};`
    ])
  );
  const rules = [
    ...themeRules(defaultTheme, true),
    ...themes.filter((entry) => entry !== defaultTheme).flatMap((entry) => themeRules(entry, false))
  ];

  return [`/* ${HEADER} */`, reset, utilities, typeComment, ...types, ...rules].join("\n\n");
}

const MOBILE_REGION = /\/\* DESIGN_TOKENS_START \*\/[\s\S]*?\/\* DESIGN_TOKENS_END \*\//;
const MOBILE_SCALE = /^(space-|radius-|font-weight-|lineHeight-|border-width|control-)/;

/** Replaces the generated region of apps/mobile/src/styles/global.css. NativeWind needs concrete values. */
export function emitMobileCss(theme: ThemeDefinition, current: string): string {
  if (!MOBILE_REGION.test(current)) {
    throw new Error("apps/mobile/src/styles/global.css has no DESIGN_TOKENS_START/END region");
  }

  const sorted = (entries: Entry[]): Entry[] => [...entries].sort(([a], [b]) => a.localeCompare(b));
  const modeNames = [...colorRoles, ...shadowRoles];
  const scale = scaleTokenNames
    .filter((name) => MOBILE_SCALE.test(name))
    .map((name): Entry => [name, theme.scale[name]]);
  const root = block(
    ":root",
    sorted([...scale, ...modeEntries(theme.modes.light, modeNames)]).map(declare)
  );
  const dark = block(".dark", sorted(modeEntries(theme.modes.dark, modeNames)).map(declare));

  return current.replace(
    MOBILE_REGION,
    `/* DESIGN_TOKENS_START */\n${root}\n\n${dark}\n/* DESIGN_TOKENS_END */`
  );
}

/**
 * packages/mobile-ui/src/lib/design-tokens.ts: every registered theme for React Native. The
 * CSS variables feed NativeWind vars(), so a subtree can switch theme and mode at runtime;
 * the palettes and fonts feed APIs that need concrete values, such as navigation.
 */
export function emitNativeTokens(
  themes: readonly ThemeDefinition[],
  defaultTheme: ThemeDefinition
): string {
  const palette = (mode: ThemeMode) => ({
    background: mode["surface-sunken"],
    surface: mode.surface,
    text: mode.text,
    subtle: mode["text-subtle"],
    border: mode.border,
    primary: mode.link,
    selected: mode["background-selected"],
    // Native SVG cannot read CSS variables, so charts take these concrete colors.
    chart: [
      mode["chart-1"],
      mode["chart-2"],
      mode["chart-3"],
      mode["chart-4"],
      mode["chart-5"],
      mode["chart-6"]
    ],
    chartGrid: mode["chart-grid"],
    track: mode["background-neutral-pressed"]
  });
  const modeNames = [...colorRoles, ...shadowRoles];
  const cssVariables = (theme: ThemeDefinition, mode: ThemeMode): Record<string, string> =>
    Object.fromEntries(
      [
        ...scaleTokenNames
          .filter((name) => MOBILE_SCALE.test(name))
          .map((name): Entry => [name, theme.scale[name]]),
        ...modeEntries(mode, modeNames)
      ].map(([name, value]) => [`--ds-${name}`, value])
    );
  const byTheme = <T>(value: (theme: ThemeDefinition) => T): Record<string, T> =>
    Object.fromEntries(themes.map((theme) => [theme.name, value(theme)]));
  const integer = (name: ScaleTokenName): number => Number.parseInt(defaultTheme.scale[name], 10);
  const json = (value: unknown): string => JSON.stringify(value, null, 2);

  return [
    `// ${HEADER}`,
    `export const defaultThemeName = ${JSON.stringify(defaultTheme.name)};`,
    `export const themeVariables = ${json(
      byTheme((theme) => ({
        light: cssVariables(theme, theme.modes.light),
        dark: cssVariables(theme, theme.modes.dark)
      }))
    )};`,
    `export const nativeThemeTokens = ${json(
      byTheme((theme) => ({ light: palette(theme.modes.light), dark: palette(theme.modes.dark) }))
    )};`,
    `export const nativeThemeFonts = ${json(byTheme((theme) => theme.nativeFonts))} as const;`,
    `export const motionDurations = ${json({
      control: integer("motion-control"),
      overlay: integer("motion-overlay"),
      drawer: integer("motion-drawer")
    })};`,
    `export const motionEasing = ${JSON.stringify(defaultTheme.scale["motion-easing"].match(/[\d.]+/g)?.map(Number))} as const;`,
    `export const motionDistances = ${JSON.stringify({
      dialog: integer("motion-distance-dialog"),
      menu: integer("motion-distance-menu")
    })};`,
    `export const motionPressScale = ${Number.parseFloat(defaultTheme.scale["motion-press-scale"])};`
  ].join("\n\n");
}

/** packages/config/tailwind/preset.tokens.js: the NativeWind utilities, named like the web ones. */
export function emitPresetTokens(theme: ThemeDefinition): string {
  const colors: Record<string, Record<string, string>> = {};

  for (const role of colorRoles) {
    const [, group = "", rest] = /^(ds-[a-z]+)(?:-(.+))?$/.exec(colorUtilityName(role)) ?? [];
    colors[group] = { ...colors[group], [rest ?? "DEFAULT"]: variable(role) };
  }

  const spacing = Object.fromEntries(
    spacingUtilities().map(([utility, token]) => [utility, variable(token)])
  );
  const boxShadow = Object.fromEntries(
    shadowRoles.map((role) => [role.replace(/^shadow-/, ""), variable(role)])
  );
  const fontSize = Object.fromEntries(
    Object.entries(typeUtilities).map(([utility, step]) => {
      const { size, lineHeight, weight } = theme.type[step];
      return [utility, [size, { lineHeight, fontWeight: String(weight) }]];
    })
  );
  const json = (value: unknown): string => JSON.stringify(value, null, 2);

  return [
    `// ${HEADER}`,
    `export const colors = ${json(colors)};`,
    `export const spacing = ${json(spacing)};`,
    `export const boxShadow = ${json(boxShadow)};`,
    `export const fontSize = ${json(fontSize)};`
  ].join("\n\n");
}
